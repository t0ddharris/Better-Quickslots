(r.BUTTON_DIR / 'rarity-button.json').write_text(json.dumps(r.b, indent=2), encoding='utf-8')

# Reverse only the inventory class rename. All appearance and update bytecode
# are generated by the same builder, including the addressable rarity local.
shared = json.loads(json.dumps(r.b).replace(r.NEW, r.OLD))

# Cooked consumers serialize instances using the stock class property order.
# Appending members to that class shifts inherited property indices in their
# unversioned data. Keep its exact schema; resolve added images through the
# existing ItemBox's parent instead of new widget-binding fields.
original = json.loads((ROOT / 'decoded/button.json').read_text(encoding='utf-8-sig'))
shared_class = r.get_exp(shared, r.OLD + '_C')
shared_class['LoadedProperties'] = r.get_exp(original, r.OLD + '_C')['LoadedProperties']
for name in r.glow_names:
    next(p for p in r.get_exp(shared, name)['Data'] if p['Name'] == 'bIsVariable')['Value'] = False

def lookup(layer):
    parent = r.ctx(r.var('ItemBox', r.owner),
                   r.ex('FinalFunction', StackNode=r.get_parent, Parameters=[]))
    child = r.ctx(parent, r.ex('FinalFunction', StackNode=r.get_child,
                              Parameters=[r.ex('IntConst', Value=layer)]))
    return r.ex('DynamicCast', ClassPtr=r.image_class, Target=child)

def replace_binding(value):
    if isinstance(value, dict):
        if 'EX_InstanceVariable,' in value.get('$type', ''):
            path = value['Variable']['New']['Path']
            if len(path) == 1 and path[0] in r.glow_names:
                return lookup(r.glow_names.index(path[0]))
        result = {k: replace_binding(v) for k, v in value.items()}
        if 'EX_Context,' in result.get('$type', ''):
            result['Offset'] = r.sz(result['ContextExpression'])
        return result
    if isinstance(value, list):
        return [replace_binding(v) for v in value]
    return value

rarity = r.get_exp(shared, 'QSH_UpdateRarity')
rarity['ScriptBytecode'] = replace_binding(rarity['ScriptBytecode'])
rarity['ScriptBytecode'][5]['CodeOffset'] = sum(map(r.sz, rarity['ScriptBytecode'][:-2]))
rarity['ScriptBytecodeSize'] = sum(map(r.sz, rarity['ScriptBytecode']))
assert shared_class['LoadedProperties'] == r.get_exp(original, r.OLD + '_C')['LoadedProperties']
# Verify that the lookup path really reaches the five added images in order.
item_box = r.get_exp(shared, 'ItemBox')
item_slot = shared['Exports'][next(p['Value'] for p in item_box['Data'] if p['Name'] == 'Slot') - 1]
parent = shared['Exports'][next(p['Value'] for p in item_slot['Data'] if p['Name'] == 'Parent') - 1]
