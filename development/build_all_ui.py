    (r.INV_DIR / 'rarity-quickslots.json', ui / 'GameHub/Inventory/WBP_Inventory_Quickslots_QSH.uasset'),
    (r.INV_DIR / 'rarity-hub.json', ui / 'GameHub/Inventory/WBP_Hub_NewInventory.uasset'),
    (shared_source, ui / 'HUD/Quickslots/WBP_HUD_Quickslots_Button.uasset'),
