# Compare the packaged functions, imports, and authored widget properties.
def properties(value):
    if isinstance(value, dict):
        return {k: properties(v) for k, v in value.items() if k != 'IsZero'}
    if isinstance(value, list):
        result = [properties(v) for v in value]
        if result and all(isinstance(v, dict) and 'Name' in v for v in result):
            result.sort(key=lambda v: v['Name'])
        return result
    if value in ('+0', '-0'):
        return 0.0
    return round(value, 6) if isinstance(value, float) else value

for source, relative in assets:
    expected = json.loads(source.read_text(encoding='utf-8-sig'))
    actual = json.loads((verified / (relative.stem + '.json')).read_text(encoding='utf-8-sig'))
    for a, b in zip(expected['Imports'], actual['Imports']):
        # The local reference set lacks Paper2D's default sprite material.
        # Retoc cannot recover those two names; they are copied unchanged
        # from the stock sprite and are resolved from the game at runtime.
        if relative == trimmed_assets[1][1] and a['ObjectName'] in (
            'TranslucentUnlitSpriteMaterial', '/Paper2D/TranslucentUnlitSpriteMaterial'
        ):
            assert b['ObjectName'] in (a['ObjectName'], 'UnknownExport', '/Engine/UnknownPackage')
            assert a['OuterIndex'] == b['OuterIndex']
        else:
            assert a == b, (relative, a, b)
    assert len(expected['Imports']) == len(actual['Imports'])
    assert len(expected['Exports']) == len(actual['Exports']), relative
    for a, b in zip(expected['Exports'], actual['Exports']):
        assert a['ObjectName'] == b['ObjectName']
        for key in ('ScriptBytecode', 'ScriptBytecodeSize', 'LoadedProperties', 'Data'):
            if key in a:
                assert properties(a[key]) == properties(b[key]), (relative, a['ObjectName'], key)
    if relative == ATLAS:
        assert expected['Exports'][0]['Extras'] == actual['Exports'][0]['Extras'], 'Inline texture mips changed'
assert len(list(stage.rglob('*.uasset'))) == 6
assert (verified / ATLAS.with_suffix('.ubulk')).read_bytes() == trimmed_bulk.read_bytes()
# Stock consumer templates must decode identically with the patched shared
# class as their dependency. This catches inherited-property schema shifts
# that comparing only our newly packaged assets cannot detect.
for relative, stock_json in (
    (ui / 'HUD/Quickslots/WBP_HUD_Quickslots.uasset', 'gameplay-quickslots.json'),
    (ui / 'GameHub/Inventory/WBP_Inventory_Quickslots.uasset', 'quickslots.json'),
):
    target = verified / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    for suffix in ('.uasset', '.uexp'):
        shutil.copy2(ROOT / 'extracted' / relative.with_suffix(suffix), target.with_suffix(suffix))
    output = verified / ('consumer-' + stock_json)
    run(gui, 'tojson', target, output, 'VER_UE5_5', 'Dawnwalker')
    stock = json.loads((ROOT / 'decoded' / stock_json).read_text(encoding='utf-8-sig'))
    recovered = json.loads(output.read_text(encoding='utf-8-sig'))
    assert len(stock['Exports']) == len(recovered['Exports'])
    for a, b in zip(stock['Exports'], recovered['Exports']):
        assert a['ObjectName'] == b['ObjectName']
        if 'Data' in a:
            assert properties(a['Data']) == properties(b['Data']), (relative, a['ObjectName'], 'stock consumer schema')
print('PASS: stock HUD and crafting quickslot templates decode unchanged against the patched class.')
# The layout and hover screen remain byte-identical; only button visuals change.
for _, relative in assets[1:3]:
    for suffix in ('.uasset', '.uexp'):
        assert (stage / relative.with_suffix(suffix)).read_bytes() == (ROOT / 'staging-v02' / relative.with_suffix(suffix)).read_bytes(), relative
for _, relative in (assets[0], assets[3]):
    actual = json.loads((verified / (relative.stem + '.json')).read_text(encoding='utf-8-sig'))
    previous = json.loads((ROOT / 'verify-v041' / (relative.stem + '.json')).read_text(encoding='utf-8-sig'))
    for a, b in zip(actual['Exports'], previous['Exports']):
        for key in ('ScriptBytecode', 'ScriptBytecodeSize', 'LoadedProperties'):
            if key in a:
                assert properties(a[key]) == properties(b[key]), (relative, a['ObjectName'], key)
    for name in ('Background', 'ItemIcon', 'ItemBox', 'StackSize'):
        assert r.get_exp(actual, name)['Data'] == r.get_exp(previous, name)['Data']
    visible = [r.get_exp(actual, name) for name in r.glow_names
               if next(p['Value'] for p in r.get_exp(actual, name)['Data'] if p['Name'] == 'Visibility') != 'Collapsed']
    assert len(visible) == 1 and visible[0]['ObjectName'] == r.glow_names[-1]
    transform = next(p for p in visible[0]['Data'] if p['Name'] == 'RenderTransform')
    scale = next(p['Value'][0]['Value'] for p in transform['Value'] if p['Name'] == 'Scale')
    assert properties(scale['X']) == 1.19 and properties(scale['Y']) == 1.19
print('PASS: one visible stock-artwork rarity outline; original bytecode, schemas, backgrounds, icons and counts preserved.')

